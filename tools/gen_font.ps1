# Renders ASCII 32..126 with a Windows font into 16x32 one-bit glyphs and
# writes them as a C header (one u16 per glyph row, MSB = leftmost pixel).
#   .\tools\gen_font.ps1 [-Font "Cascadia Mono"] [-Size 26] [-Out app\font.h]
# The default, Cascadia Mono (Windows 11), is under the SIL Open Font License
# 1.1 (THIRD_PARTY_NOTICES.md); use only fonts whose licence allows this.
param(
    [string]$Font = "Cascadia Mono",
    [float]$Size = 26,
    [string]$Out = "$PSScriptRoot\..\app\font.h"
)

Add-Type -AssemblyName System.Drawing

$cellW = 16
$cellH = 32
$bmp = New-Object System.Drawing.Bitmap $cellW, $cellH
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
$fnt = New-Object System.Drawing.Font($Font, $Size, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
if ($fnt.Name -ne $Font) { throw "font '$Font' is not installed (got '$($fnt.Name)')" }
$fmt = [System.Drawing.StringFormat]::GenericTypographic

$lines = @()
$lines += "// Generated by tools/gen_font.ps1 from '$Font' $Size px. Do not edit."
$lines += "// Glyphs for ASCII 32..126, $cellW x $cellH, one u16 per row, MSB = left."
$lines += "#pragma once"
$lines += ""
$lines += "enum { kFontFirstChar = 32, kFontLastChar = 126, kFontCellW = $cellW, kFontCellH = $cellH };"
$lines += ""
$lines += "static const unsigned short g_font[kFontLastChar - kFontFirstChar + 1][kFontCellH] ="
$lines += "{"

for ($c = 32; $c -le 126; $c++) {
    $g.Clear([System.Drawing.Color]::Black)
    $ch = [string][char]$c
    $w = $g.MeasureString($ch, $fnt, 1000, $fmt).Width
    $x = [Math]::Max(0, [Math]::Floor(($cellW - $w) / 2))
    $g.DrawString($ch, $fnt, [System.Drawing.Brushes]::White, $x, 1, $fmt)

    $rows = @()
    for ($y = 0; $y -lt $cellH; $y++) {
        $bits = 0
        for ($px = 0; $px -lt $cellW; $px++) {
            if ($bmp.GetPixel($px, $y).R -gt 127) { $bits = $bits -bor (0x8000 -shr $px) }
        }
        $rows += ('0x{0:X4}' -f $bits)
    }
    $label = if ($c -eq 92) { "backslash" } else { "'$ch'" }
    $lines += "    { " + ($rows -join ", ") + " }, // $label"
}

$lines += "};"
$g.Dispose(); $bmp.Dispose()

New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
$lines | Set-Content -Encoding ascii $Out
Write-Host "Wrote $Out"
