# Renders the main menu's card pictures (tools/menu_art.html) with Edge,
# headless, to 364x190 PNGs with transparent corners and writes them as a C
# header of PNG bytes, decoded by the app at start.
#   .\tools\gen_menu_art.ps1 [-Out app\menu_art.h]
param(
    [string]$Out = "$PSScriptRoot\..\app\menu_art.h"
)

$ErrorActionPreference = "Stop"
$edge = @("${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
          "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $edge) { throw "Microsoft Edge is not installed" }
$page = ([System.Uri](Resolve-Path "$PSScriptRoot\menu_art.html").Path).AbsoluteUri
$temp = Join-Path ([System.IO.Path]::GetTempPath()) "menu_art"
New-Item -ItemType Directory -Force $temp | Out-Null

$names = @("Unlock Items", "Activate Offline Profile", "Avatar Editor")
$lines = @()
$lines += "// Generated by tools/gen_menu_art.ps1 from tools/menu_art.html. Do not edit."
$lines += "// The main menu cards' pictures as PNGs, 364 x 190, in menu order."
$lines += "#pragma once"
$lines += ""
for ($i = 0; $i -lt 3; $i++) {
    $png = Join-Path $temp "tile$i.png"
    if (Test-Path $png) { Remove-Item -LiteralPath $png -Confirm:$false }
    $arguments = @("--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                   "--default-background-color=00000000", "--window-size=364,190", "--virtual-time-budget=3000",
                   "--user-data-dir=`"$temp\profile`"", "--screenshot=`"$png`"", "$page#$i")
    Start-Process -FilePath $edge -ArgumentList $arguments -Wait -WindowStyle Hidden
    if (-not (Test-Path $png)) { throw "Edge did not write $png" }

    $bytes = [System.IO.File]::ReadAllBytes($png)
    $lines += "// $($names[$i])"
    $lines += "static const unsigned char g_menuArt$i[$($bytes.Length)] ="
    $lines += "{"
    for ($o = 0; $o -lt $bytes.Length; $o += 24) {
        $row = $bytes[$o..([Math]::Min($o + 23, $bytes.Length - 1))] | ForEach-Object { "0x{0:X2}" -f $_ }
        $lines += "    " + ($row -join ", ") + ","
    }
    $lines += "};"
    $lines += ""
}
$lines += "static const unsigned char* const g_menuArt[3] = { g_menuArt0, g_menuArt1, g_menuArt2 };"
$lines += "static const unsigned int g_menuArtSize[3] = { sizeof g_menuArt0, sizeof g_menuArt1, sizeof g_menuArt2 };"
[System.IO.File]::WriteAllLines((Join-Path (Resolve-Path (Split-Path $Out)) (Split-Path $Out -Leaf)), $lines)
Write-Host "Wrote $Out"
